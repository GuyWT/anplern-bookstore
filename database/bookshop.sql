SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS payment, order_status_log, order_item, orders, cart_item, coupon, promotion, book, category, member;
SET FOREIGN_KEY_CHECKS = 1;

-- สมาชิก (ลูกค้า/ผู้ดูแลระบบ) สมัครใหม่ได้สิทธิ์เริ่มต้นเป็น customer
CREATE TABLE member (
  member_id     INT AUTO_INCREMENT PRIMARY KEY,
  first_name    VARCHAR(50)  NOT NULL,
  last_name     VARCHAR(50)  NOT NULL,
  email         VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  phone         VARCHAR(20)  NOT NULL,
  address       TEXT         NOT NULL,
  role          ENUM('customer','admin') NOT NULL DEFAULT 'customer',
  created_at    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- หมวดหมู่หนังสือ
CREATE TABLE category (
  category_id   INT AUTO_INCREMENT PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- หนังสือ (ภาพปกเก็บเป็นไฟล์ img/<book_id>.jpg)
CREATE TABLE book (
  book_id     INT AUTO_INCREMENT PRIMARY KEY,
  title       VARCHAR(200)  NOT NULL,
  author      VARCHAR(150)  NOT NULL,
  category_id INT           NOT NULL,
  price       DECIMAL(10,2) NOT NULL,
  stock       INT           NOT NULL DEFAULT 0,
  description TEXT,
  added_date  DATE          NOT NULL COMMENT 'วันที่นำเข้าระบบ ใช้คำนวณสินค้าค้างสต็อก',
  FOREIGN KEY (category_id) REFERENCES category(category_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- โปรโมชั่นอัตโนมัติ 3 ประเภท
--   tier      : ลดทั้งตะกร้าเมื่อยอดซื้อถึง min_spend (ใช้ขั้นที่สูงที่สุดที่ถึง)
--   seasonal  : แคมเปญตามเทศกาล ลดเฉพาะหมวด category_id (NULL = ทุกหมวด)
--   clearance : ล้างสต็อก ลดหนังสือที่อยู่ในคลัง >= min_days_in_stock วัน และเหลือ <= max_stock เล่ม
--   ระดับสินค้า: ใช้ seasonal/clearance ที่ลดมากที่สุดเพียง 1 รายการต่อเล่ม แล้วจึงคิด tier และคูปองตามลำดับ
CREATE TABLE promotion (
  promo_id          INT AUTO_INCREMENT PRIMARY KEY,
  promo_name        VARCHAR(150) NOT NULL,
  promo_type        ENUM('tier','seasonal','clearance') NOT NULL,
  discount_percent  DECIMAL(5,2) NOT NULL,
  min_spend         DECIMAL(10,2) NULL,
  category_id       INT NULL,
  min_days_in_stock INT NULL,
  max_stock         INT NULL,
  start_date        DATE NOT NULL,
  end_date          DATE NOT NULL,
  is_active         TINYINT(1) NOT NULL DEFAULT 1,
  FOREIGN KEY (category_id) REFERENCES category(category_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- คูปองส่วนลด (ตรวจวันหมดอายุ ยอดขั้นต่ำ และสิทธิ์คงเหลือ = usage_limit - จำนวนครั้งที่ใช้)
CREATE TABLE coupon (
  coupon_code    VARCHAR(20) PRIMARY KEY,
  description    VARCHAR(150),
  discount_type  ENUM('percent','fixed') NOT NULL,
  discount_value DECIMAL(10,2) NOT NULL,
  max_discount   DECIMAL(10,2) NULL,
  min_spend      DECIMAL(10,2) NOT NULL DEFAULT 0,
  usage_limit    INT NOT NULL,
  start_date     DATE NOT NULL,
  end_date       DATE NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ตะกร้าสินค้า
CREATE TABLE cart_item (
  member_id INT NOT NULL,
  book_id   INT NOT NULL,
  quantity  INT NOT NULL DEFAULT 1,
  added_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (member_id, book_id),
  FOREIGN KEY (member_id) REFERENCES member(member_id) ON DELETE CASCADE,
  FOREIGN KEY (book_id)   REFERENCES book(book_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- คำสั่งซื้อ (เก็บยอดและส่วนลดแต่ละชั้น ณ วันที่สั่ง)
CREATE TABLE orders (
  order_id        INT AUTO_INCREMENT PRIMARY KEY,
  member_id       INT NOT NULL,
  order_date      DATETIME NOT NULL,
  ship_address    TEXT NOT NULL,
  subtotal        DECIMAL(10,2) NOT NULL COMMENT 'ราคารวมก่อนหักส่วนลด',
  item_discount   DECIMAL(10,2) NOT NULL DEFAULT 0 COMMENT 'ส่วนลดระดับสินค้า (เทศกาล/ล้างสต็อก)',
  promo_id        INT NULL COMMENT 'โปรฯ ยอดซื้อขั้นบันได (tier)',
  tier_discount   DECIMAL(10,2) NOT NULL DEFAULT 0,
  coupon_code     VARCHAR(20) NULL,
  coupon_discount DECIMAL(10,2) NOT NULL DEFAULT 0,
  net_total       DECIMAL(10,2) NOT NULL,
  status          ENUM('pending','packing','shipped','delivered','cancelled') NOT NULL DEFAULT 'pending',
  carrier         VARCHAR(50) NULL,
  tracking_no     VARCHAR(30) NULL,
  FOREIGN KEY (member_id)   REFERENCES member(member_id),
  FOREIGN KEY (promo_id)    REFERENCES promotion(promo_id),
  FOREIGN KEY (coupon_code) REFERENCES coupon(coupon_code) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- รายการหนังสือในคำสั่งซื้อ
CREATE TABLE order_item (
  order_id        INT NOT NULL,
  book_id         INT NOT NULL,
  quantity        INT NOT NULL,
  unit_price      DECIMAL(10,2) NOT NULL COMMENT 'ราคาต่อเล่ม ณ วันที่สั่ง',
  promo_id        INT NULL COMMENT 'โปรฯ ระดับสินค้าที่ได้รับ',
  discount_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  PRIMARY KEY (order_id, book_id),
  FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE CASCADE,
  FOREIGN KEY (book_id)  REFERENCES book(book_id),
  FOREIGN KEY (promo_id) REFERENCES promotion(promo_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ประวัติสถานะคำสั่งซื้อ/พัสดุ (ใช้แสดง timeline การติดตาม)
CREATE TABLE order_status_log (
  log_id     INT AUTO_INCREMENT PRIMARY KEY,
  order_id   INT NOT NULL,
  status     ENUM('pending','packing','shipped','delivered','cancelled') NOT NULL,
  note       VARCHAR(255),
  changed_at DATETIME NOT NULL,
  changed_by INT NULL COMMENT 'admin ที่อัปเดต (NULL = ระบบ/ลูกค้า)',
  FOREIGN KEY (order_id)   REFERENCES orders(order_id) ON DELETE CASCADE,
  FOREIGN KEY (changed_by) REFERENCES member(member_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- การชำระเงินผ่าน Payment Gateway (จำลอง) คำสั่งซื้อละ 1 รายการ
--   ร้านสร้างคำสั่งซื้อหลังจากชำระเงินสำเร็จแล้วเท่านั้น
--   ถ้ายกเลิกคำสั่งซื้อ สถานะการชำระเงินเปลี่ยนเป็น refunded (คืนเงิน)
CREATE TABLE payment (
  payment_id  INT AUTO_INCREMENT PRIMARY KEY,
  order_id    INT NOT NULL UNIQUE,
  method      ENUM('card','promptpay') NOT NULL,
  amount      DECIMAL(10,2) NOT NULL,
  status      ENUM('paid','refunded') NOT NULL DEFAULT 'paid',
  ref_no      VARCHAR(30) NOT NULL UNIQUE COMMENT 'เลขอ้างอิงจาก Payment Gateway',
  card_last4  CHAR(4) NULL COMMENT 'เลขบัตร 4 ตัวท้าย (ไม่เก็บเลขบัตรเต็ม)',
  paid_at     DATETIME NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

